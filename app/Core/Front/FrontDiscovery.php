<?php

namespace App\Core\Front;

use XMLWriter;

/**
 * The generated discovery files of a front: robots.txt (policy from facts.discovery),
 * sitemap.xml (every indexable page with hreflang alternates), llms.txt and llms-full.txt.
 */
class FrontDiscovery
{
    /**
     * Crawlers that fetch pages to answer a user (AI search and assistants).
     */
    private const AI_SEARCH_AGENTS = [
        'OAI-SearchBot',
        'ChatGPT-User',
        'Claude-SearchBot',
        'Claude-User',
        'PerplexityBot',
        'Perplexity-User',
    ];

    /**
     * Crawlers that collect pages to train models.
     */
    private const AI_TRAINING_AGENTS = [
        'GPTBot',
        'ClaudeBot',
        'Google-Extended',
        'Applebot-Extended',
        'CCBot',
        'meta-externalagent',
    ];

    public function robots(FrontSite $site): string
    {
        $root = $site->rootPath();

        $lines = [
            '# Generated by the Shopmade front kit from facts.discovery. Edit facts.yaml, not this file.',
            'User-agent: *',
            sprintf(
                'Content-Signal: search=yes, ai-input=%s, ai-train=%s',
                $site->allowsAiSearch() ? 'yes' : 'no',
                $site->allowsAiTraining() ? 'yes' : 'no',
            ),
            'Allow: '.$root,
            '',
            '# AI search and assistants (facts.discovery.ai_search: '.($site->allowsAiSearch() ? 'true' : 'false').')',
            ...array_map(fn (string $agent): string => 'User-agent: '.$agent, self::AI_SEARCH_AGENTS),
            ($site->allowsAiSearch() ? 'Allow: ' : 'Disallow: ').$root,
            '',
            '# AI training (facts.discovery.ai_training: '.($site->allowsAiTraining() ? 'true' : 'false').')',
            ...array_map(fn (string $agent): string => 'User-agent: '.$agent, self::AI_TRAINING_AGENTS),
            ($site->allowsAiTraining() ? 'Allow: ' : 'Disallow: ').$root,
            '',
            'Sitemap: '.$site->fileUrl('sitemap.xml'),
        ];

        return implode("\n", $lines)."\n";
    }

    public function sitemap(FrontSite $site): string
    {
        $xml = new XMLWriter;
        $xml->openMemory();
        $xml->setIndent(true);
        $xml->setIndentString('  ');
        $xml->startDocument('1.0', 'UTF-8');
        $xml->startElement('urlset');
        $xml->writeAttribute('xmlns', 'http://www.sitemaps.org/schemas/sitemap/0.9');
        $xml->writeAttribute('xmlns:xhtml', 'http://www.w3.org/1999/xhtml');

        foreach ($site->indexablePages() as $page) {
            $xml->startElement('url');
            $xml->writeElement('loc', $site->url($page['slug'], $page['lang']));

            foreach ($this->indexableAlternates($site, $page['slug']) as $alternate) {
                $xml->startElement('xhtml:link');
                $xml->writeAttribute('rel', 'alternate');
                $xml->writeAttribute('hreflang', $alternate['lang']);
                $xml->writeAttribute('href', $alternate['url']);
                $xml->endElement();
            }

            $xml->endElement();
        }

        $xml->endElement();
        $xml->endDocument();

        return $xml->outputMemory();
    }

    public function llms(FrontSite $site): string
    {
        $lines = [
            '# '.$this->line($site->name()),
            '',
            '> '.$this->line($site->summary()),
            '',
            ...$this->factLines($site),
            '',
            'Every page below also answers `Accept: text/markdown` with its markdown source.',
        ];

        foreach ($site->languages() as $lang) {
            $pages = array_filter($site->indexablePages(), fn (array $page): bool => $page['lang'] === $lang);

            if ($pages === []) {
                continue;
            }

            $lines[] = '';
            $lines[] = '## Pages ('.$lang.')';
            $lines[] = '';

            foreach ($pages as $page) {
                $description = $site->text($page['frontmatter']['description'] ?? null);

                $lines[] = sprintf(
                    '- [%s](%s)%s',
                    $this->linkText($site->text($page['frontmatter']['title'] ?? null) ?? $page['slug']),
                    $site->url($page['slug'], $page['lang']),
                    $description !== null ? ': '.$description : '',
                );
            }
        }

        array_push(
            $lines,
            '',
            '## Optional',
            '',
            '- [Full text of every page]('.$site->fileUrl('llms-full.txt').')',
            '- [Sitemap]('.$site->fileUrl('sitemap.xml').')',
        );

        return implode("\n", $lines)."\n";
    }

    public function llmsFull(FrontSite $site): string
    {
        $lines = [
            '# '.$this->line($site->name()).' — full text',
            '',
            '> '.$this->line($site->summary()),
            '',
            ...$this->factLines($site),
        ];

        foreach ($site->indexablePages() as $page) {
            array_push(
                $lines,
                '',
                '---',
                '',
                'Page: '.($site->text($page['frontmatter']['title'] ?? null) ?? $page['slug']),
                'URL: '.$site->url($page['slug'], $page['lang']),
                'Language: '.$page['lang'],
                '',
                $site->bodyMarkdown($page),
            );
        }

        return implode("\n", $lines)."\n";
    }

    /**
     * hreflang alternates of a page among its indexable versions, plus x-default.
     *
     * @return list<array{lang: string, url: string}>
     */
    private function indexableAlternates(FrontSite $site, string $slug): array
    {
        $alternates = [];

        foreach ($site->translations($slug) as $lang => $page) {
            if ($site->isIndexable($page)) {
                $alternates[] = ['lang' => $lang, 'url' => $site->url($slug, $lang)];
            }
        }

        $default = $site->translations($slug)[$site->defaultLanguage()] ?? null;

        if ($default !== null && $site->isIndexable($default)) {
            $alternates[] = ['lang' => 'x-default', 'url' => $site->url($slug, $site->defaultLanguage())];
        }

        return $alternates;
    }

    /**
     * @return list<string>
     */
    private function factLines(FrontSite $site): array
    {
        $facts = [
            'Phone' => $site->phone(),
            'Email' => $site->email(),
            'Address' => $site->publishesAddress() && $site->address() !== null ? implode(', ', $site->address()) : null,
            'Service area' => implode(', ', $site->cities()),
            'Services' => implode(', ', array_column($site->services($site->defaultLanguage()), 'name')),
            'Languages' => implode(', ', $site->languages()),
            'Hours' => implode('; ', $site->hours()),
        ];

        $lines = [];

        foreach ($facts as $label => $value) {
            if ($value !== null && $value !== '') {
                $lines[] = '- '.$label.': '.$this->line($value);
            }
        }

        return $lines;
    }

    private function line(string $text): string
    {
        return trim((string) preg_replace('/\s+/u', ' ', $text));
    }

    private function linkText(string $text): string
    {
        return str_replace(['[', ']'], ['\[', '\]'], $this->line($text));
    }
}
